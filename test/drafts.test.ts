import { afterEach, expect, test } from "bun:test";
import { itemDocument } from "../src/blyg";
import { handleDraftRequest } from "../src/drafts";
import { changelog, getItem } from "../src/store";
import { handleUpdate, type TgMessage } from "../src/telegram";
import { d1 } from "./d1";

const SITE = { origin: "https://me.example/blyg/", title: "me", subtitle: "", author: { name: "me", url: "https://me.example/" } };
const CFG = { token: "t", chatId: -100, pubTopicId: 2, subTopicId: 3, ownerId: 1 };
const TOKEN = "s3cret";

// a Telegram that records each call and numbers the bot's messages from 500
type Call = { method: string; body: Record<string, unknown> };
function bot() {
  const calls: Call[] = [];
  let next = 500;
  globalThis.fetch = (async (url: string, init?: RequestInit) => {
    const method = String(url).split("/").pop()!;
    const body = init?.body instanceof FormData ? Object.fromEntries(init.body as unknown as Iterable<[string, unknown]>) : JSON.parse(String(init?.body));
    calls.push({ method, body });
    return Response.json({ ok: true, result: { message_id: next++ } });
  }) as typeof fetch;
  return calls;
}
const realFetch = globalThis.fetch;
afterEach(() => { globalThis.fetch = realFetch; });

const submit = (db: ReturnType<typeof d1>, body: unknown, auth = `Bearer ${TOKEN}`) =>
  handleDraftRequest(new Request("https://w.example/api/drafts", { method: "POST", headers: { authorization: auth }, body: JSON.stringify(body) }), db, SITE, CFG, TOKEN);

let nextId = 1;
async function command(db: ReturnType<typeof d1>, text: string, replyTo?: number, from = 500) {
  const message: TgMessage = {
    message_id: nextId++, message_thread_id: 2, from: { id: 1 }, chat: { id: -100 }, text,
    ...(replyTo ? { reply_to_message: { message_id: replyTo, from: { id: from }, chat: { id: -100 }, text: "📝 draft · fragment" } } : {}),
  };
  const after = await handleUpdate({ update_id: nextId++, message }, db, SITE, CFG);
  await after?.();
}
const replies = (calls: Call[]) => calls.filter((c) => c.method === "sendMessage").map((c) => String(c.body.text));

test("only the token holder can submit, and only when a token is set", async () => {
  const db = d1();
  bot();
  expect((await submit(db, { content_md: "hi" }, "Bearer nope")).status).toBe(401);
  expect((await submit(db, { content_md: "hi" }, "")).status).toBe(401);
  const off = await handleDraftRequest(new Request("https://w.example/api/drafts", { method: "POST", body: "{}" }), db, SITE, CFG, undefined);
  expect(off.status).toBe(404);
  expect(db.sqlite.query("SELECT COUNT(*) n FROM drafts").get()).toEqual({ n: 0 });
});

test("a draft waits in Pub and publishes only on /publish, disclosed as generated", async () => {
  const db = d1();
  const calls = bot();
  const res = await submit(db, { content_md: "Today blyxt learned **drafts**.", generated: { model: "claude-opus-5-5", at: "2026-10-13T00:00:00.000Z", prompt: "write it up" } });
  expect(res.status).toBe(201);
  expect(await res.json()).toMatchObject({ kind: "fragment", message_id: 500 });
  expect(calls[0].body).toMatchObject({ chat_id: -100, message_thread_id: 2 });
  expect(String(calls[0].body.text)).toStartWith("📝 <b>draft</b> · fragment · 31 characters\ngenerated by claude-opus-5-5: it publishes marked as machine-generated\n\nToday blyxt learned <b>drafts</b>.");
  expect(db.sqlite.query("SELECT COUNT(*) n FROM items").get()).toEqual({ n: 0 }); // invisible to the protocol

  await command(db, "/publish", 500);
  const { item_id } = db.sqlite.query("SELECT item_id FROM tg_messages WHERE message_id = 500").get() as { item_id: string };
  const doc = itemDocument(SITE, (await getItem(db, item_id))!, await changelog(db, item_id));
  // the prompt is studio-private: only sources, model and at reach the wire
  expect(doc.generated).toEqual([{ sources: [], model: "claude-opus-5-5", at: "2026-10-13T00:00:00Z" }]);
  expect(doc.content_html).toStartWith('<div class="blyg-tk-gen">');
  expect(replies(calls).at(-1)).toBe(`published v1 (marked machine-generated) → https://me.example/blyg/f/${item_id}/`);
  expect(db.sqlite.query("SELECT COUNT(*) n FROM drafts").get()).toEqual({ n: 0 });

  // a retried /publish doesn't publish twice
  await command(db, "/publish", 500);
  expect(db.sqlite.query("SELECT COUNT(*) n FROM items").get()).toEqual({ n: 1 });
  expect(replies(calls).at(-1)).toBe(`already published → https://me.example/blyg/f/${item_id}/`);

  // the preview stands for the post: withdraw and republish it there, and the disclosure comes back with it
  await command(db, "/withdraw", 500);
  expect("generated" in itemDocument(SITE, (await getItem(db, item_id))!, [])).toBe(false);
  await command(db, "/republish", 500);
  const back = (await getItem(db, item_id))!;
  expect([back.version, back.content_md, JSON.parse(back.generated!)[0].model]).toEqual([3, "Today blyxt learned **drafts**.", "claude-opus-5-5"]);
});

test("/discard deletes the draft and its preview; nothing is published", async () => {
  const db = d1();
  const calls = bot();
  await submit(db, { content_md: "never mind" });
  await command(db, "/discard", 500);
  expect(calls.filter((c) => c.method === "deleteMessage").map((c) => c.body.message_id)).toEqual([500]);
  expect(replies(calls).at(-1)).toBe("discarded the draft; nothing was published");
  expect(db.sqlite.query("SELECT (SELECT COUNT(*) FROM drafts) + (SELECT COUNT(*) FROM items) n").get()).toEqual({ n: 0 });
});

test("a long draft previews cut short with the whole markdown attached, and publishes as a thread", async () => {
  const db = d1();
  const calls = bot();
  const md = "word ".repeat(1000).trim();
  await submit(db, { content_md: md });
  expect(String(calls[0].body.text)).toStartWith("📝 <b>draft</b> · thread (over 2,000 characters) · 4,999 characters\n\nword");
  expect(calls[1].method).toBe("sendDocument");
  expect(await (calls[1].body.document as File).text()).toBe(md);
  await command(db, "/publish", 501); // replying to the file works too
  const item = db.sqlite.query("SELECT kind, generated FROM items").get();
  expect(item).toEqual({ kind: "thread", generated: null });
});

test("a draft's provenance is checked before it reaches Pub", async () => {
  const db = d1();
  const calls = bot();
  const bad = async (body: unknown) => (await (await submit(db, body)).json() as { error: string }).error;
  expect(await bad({ content_md: "" })).toBe("content_md is required");
  expect(await bad({ content_md: "x", generated: { sources: [{ id: "0000000000000000000000000u", version: 1 }] } })).toBe("each source is { id, version } of a post on this blyg");
  expect(await bad({ content_md: "x", generated: { sources: [{ id: "00000000000000000000000000", version: 1 }] } })).toBe("00000000000000000000000000 v1 isn't a published version on this blyg");
  expect(await bad({ content_md: "![[00000000000000000000000000]]\n\nsee", generated: {} })).toBe("a generated draft can't quote yet: blyxt marks the whole body as generated");
  expect(calls).toEqual([]);
});

test("/publish and /discard need a draft to reply to", async () => {
  const db = d1();
  const calls = bot();
  await command(db, "/publish");
  await command(db, "/discard", 42);
  expect(replies(calls)).toEqual(["reply /publish to a draft's preview", "reply /discard to a draft's preview"]);
});
